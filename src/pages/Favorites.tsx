import { useState } from "react";
import { Heart, Download, Copy, Check } from "lucide-react";
import { PackageGrid } from "@/components/package/PackageGrid";
import { TagDialog } from "@/components/common/TagDialog";
import { Button } from "@/components/ui/button";
import { useSearchPackages, type PackageItem } from "@/hooks/usePackages";
import { useSearchStore } from "@/stores/useSearchStore";
import { useCardNavigation } from "@/hooks/useCardNavigation";
import { useSEO } from "@/hooks/useSEO";
import { toast } from "sonner";

function buildBrewfile(packages: PackageItem[]): string {
  const formulae = packages
    .filter((p) => p.type === "formula")
    .map((p) => p.name)
    .sort();
  const casks = packages
    .filter((p) => p.type === "cask")
    .map((p) => p.name)
    .sort();
  const lines: string[] = [
    "# Generated by Brew Graph",
    `# ${new Date().toISOString()}`,
    "",
  ];
  if (formulae.length > 0) {
    for (const f of formulae) lines.push(`brew "${f}"`);
    if (casks.length > 0) lines.push("");
  }
  for (const c of casks) lines.push(`cask "${c}"`);
  lines.push("");
  return lines.join("\n");
}

export function Favorites() {
  const { hideDeprecated, selectedIndex } = useSearchStore();

  useSEO({
    title: "Favorites",
    description: "Your favorite Homebrew packages",
  });
  const [tagDialogPkg, setTagDialogPkg] = useState<PackageItem | null>(null);
  const [copied, setCopied] = useState(false);
  // Large limit so the export covers everyone — anything < ~10k is fine.
  const packages = useSearchPackages(
    "",
    "all",
    null,
    true,
    hideDeprecated,
    100000
  );

  const { containerRef } = useCardNavigation({
    packages,
    onTagRequest: (pkg) => setTagDialogPkg(pkg),
  });

  const handleCopy = async () => {
    if (!packages || packages.length === 0) return;
    const content = buildBrewfile(packages);
    try {
      await navigator.clipboard.writeText(content);
      setCopied(true);
      toast.success("Brewfile copied to clipboard");
      setTimeout(() => setCopied(false), 1500);
    } catch {
      toast.error("Failed to copy");
    }
  };

  const handleDownload = () => {
    if (!packages || packages.length === 0) return;
    const content = buildBrewfile(packages);
    const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "Brewfile";
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  };

  const hasItems = !!packages && packages.length > 0;

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <Heart className="h-5 w-5 text-red-500 fill-red-500" />
          <h1 className="text-2xl font-bold">Favorites</h1>
        </div>
        {hasItems && (
          <div className="flex items-center gap-2">
            <Button
              variant="outline"
              size="sm"
              onClick={handleCopy}
              title="Copy as Brewfile"
            >
              {copied ? (
                <Check className="h-4 w-4 mr-2" />
              ) : (
                <Copy className="h-4 w-4 mr-2" />
              )}
              Copy Brewfile
            </Button>
            <Button
              variant="outline"
              size="sm"
              onClick={handleDownload}
              title="Download as Brewfile"
            >
              <Download className="h-4 w-4 mr-2" />
              Download
            </Button>
          </div>
        )}
      </div>

      {packages && packages.length === 0 ? (
        <div className="text-center py-12">
          <Heart className="h-12 w-12 mx-auto text-muted-foreground mb-4" />
          <h2 className="text-lg font-semibold mb-2">No favorites yet</h2>
          <p className="text-muted-foreground">
            Press F on any package to add it to your favorites.
          </p>
        </div>
      ) : (
        <PackageGrid
          ref={containerRef}
          packages={packages}
          selectedIndex={selectedIndex}
          onTagRequest={(pkg) => setTagDialogPkg(pkg)}
        />
      )}

      <TagDialog
        pkg={tagDialogPkg}
        open={!!tagDialogPkg}
        onOpenChange={(open) => !open && setTagDialogPkg(null)}
      />
    </div>
  );
}
